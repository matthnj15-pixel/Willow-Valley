import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {NodeIO} from '@gltf-transform/core';
import {prune} from '@gltf-transform/functions';
import {validateBytes} from 'gltf-validator';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));process.chdir(root);
const hash=b=>createHash('sha256').update(b).digest('hex');
execFileSync(process.execPath,['scripts/validate-wv007-adoption.mjs'],{stdio:'pipe'});
const selection=JSON.parse(await readFile('render-adoption/selection.json','utf8'));
const source=selection.sources.landscape,manifest=JSON.parse(await readFile(source.manifest,'utf8'));
const out='assets/wv/runtime-landscape-v1';await mkdir(out,{recursive:true});
const io=new NodeIO(),outputs={};
for(const lod of ['normal','low','far']){
  const doc=await io.read(source.bundle);
  for(const node of doc.getRoot().listNodes())if(!node.getName().endsWith('__'+lod))node.dispose();
  await doc.transform(prune());
  const bytes=await io.writeBinary(doc),validation=await validateBytes(bytes);
  if(validation.issues.numErrors||validation.issues.numWarnings)throw Error(JSON.stringify(validation.issues));
  const file=`${lod}.glb`;await writeFile(`${out}/${file}`,bytes);
  outputs[lod]={path:`${out}/${file}`,sha256:hash(bytes),bytes:bytes.length,textures:0,
    nodes:doc.getRoot().listNodes().map(n=>n.getName()),triangles:manifest.entries.reduce((n,e)=>n+e.variants.find(v=>v.lod===lod).triangles,0)};
}
const sourcePaths=[source.manifest,source.bundle,'scripts/build-wv007-landscape.mjs',...selection.sourcePins.filter(p=>p.path.startsWith('assets/wv/landscape-next/')&&!p.path.endsWith('hamlet-scene.mjs')).map(p=>p.path)];
const sourcePins=await Promise.all(sourcePaths.map(async p=>({path:p,sha256:hash(await readFile(p))})));
const data={revision:'wv007-p3-landscape-1',contractRevision:1,runtimeReady:false,units:'visual metres',gameUnitsPerMetre:2.8,
  parent:source,sourcePins,outputs,entries:manifest.entries};
await writeFile(`${out}/manifest.json`,JSON.stringify(data,null,2)+'\n');
await writeFile(`${out}/metadata.mjs`,'// Generated by scripts/build-wv007-landscape.mjs\nexport default '+JSON.stringify(data)+';\n');
// Exact recursive ESM closure, including code used by the frozen specialized planners.
const visited=new Set();
async function visit(p){
  if(visited.has(p))return;visited.add(p);
  const text=await readFile(p,'utf8');
  for(const match of text.matchAll(/(?:from\s*|import\s*)['"]([^'"]+)['"]/g))if(match[1].startsWith('.')){
    const target=path.posix.normalize(path.posix.join(path.posix.dirname(p),match[1].split('?')[0]));await visit(target);
  }
}
await visit('render-adoption/landscape/index.mjs');
const code=await Promise.all([...visited].sort().map(async p=>{const b=await readFile(p);return {path:p,sha256:hash(b),bytes:b.length};}));
const assetMetadata=await Promise.all([`${out}/manifest.json`].map(async p=>{const b=await readFile(p);return {path:p,sha256:hash(b),bytes:b.length};}));
const closure={revision:data.revision,entry:'render-adoption/landscape/index.mjs',code,metadata:assetMetadata,
  profiles:Object.fromEntries(Object.entries(outputs).map(([q,o])=>[q,{assets:[o],totalBytes:code.reduce((n,c)=>n+c.bytes,0)+assetMetadata.reduce((n,c)=>n+c.bytes,0)+o.bytes,textureBytes:0}])),
  offlineAdmitted:false,excluded:['authored hamlet layouts','source landscape.glb','C1/C2/C3/C4 building bundles','remote runtime resources']};
await writeFile(`${out}/closure.json`,JSON.stringify(closure,null,2)+'\n');
console.log(JSON.stringify(Object.fromEntries(Object.entries(outputs).map(([q,o])=>[q,{bytes:o.bytes,triangles:o.triangles}]))));
